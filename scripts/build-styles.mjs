/*
 * Builds the root styles.css from src/styles.css, with the three typefaces
 * embedded as data: URIs. Obsidian ships a plugin as main.js + manifest.json +
 * styles.css only, so embedding is the one way to keep the design without a
 * request to a font CDN every time the plugin loads.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/* family -> weights actually used by src/styles.css */
export const FONTS = [
  { pkg: "@fontsource/syne", weights: [700, 800] },
  { pkg: "@fontsource/dm-sans", weights: [400, 500, 600] },
  { pkg: "@fontsource/dm-mono", weights: [400, 500] },
];
export const SUBSETS = ["latin", "latin-ext"];

function fontFaces({ pkg, weights }) {
  const dir = dirname(require.resolve(`${pkg}/package.json`));
  const out = [];
  for (const weight of weights) {
    const css = readFileSync(join(dir, `${weight}.css`), "utf8");
    for (const subset of SUBSETS) {
      /* one @font-face block per subset, introduced by "/* <id>-<subset>-<weight>-normal *​/" */
      const block = css.split("/*").find((b) => new RegExp(`^ [a-z-]+?-${subset}-${weight}-normal \\*/`).test(b));
      if (!block) throw new Error(`${pkg}: no ${subset} ${weight} @font-face block`);
      const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
      const file = /url\(\.\/(files\/[^)]+\.woff2)\)/.exec(block)?.[1];
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
      if (!family || !file || !range) throw new Error(`${pkg}: could not parse ${subset} ${weight} block`);
      const b64 = readFileSync(join(dir, file)).toString("base64");
      out.push(
        `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};` +
        `src:url(data:font/woff2;base64,${b64}) format('woff2');unicode-range:${range}}`
      );
    }
  }
  return out;
}

export function buildStyles() {
  const src = readFileSync(join(root, "src/styles.css"), "utf8");
  if (/@import|url\((?!\s*['"]?data:)/i.test(src)) {
    throw new Error("src/styles.css must not @import or reference a url() that is not a data: URI");
  }
  const banner =
    "/* GENERATED by `npm run build` from src/styles.css - edit that file, not this one.\n" +
    " * Typefaces (Syne, DM Sans, DM Mono; SIL Open Font License 1.1, see licenses/) are embedded\n" +
    " * as data: URIs, so this stylesheet itself references nothing remote. */\n";
  const css = banner + FONTS.flatMap(fontFaces).join("\n") + "\n\n" + src;
  writeFileSync(join(root, "styles.css"), css);
  return css.length;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`  styles.css  ${(buildStyles() / 1024).toFixed(1)}kb`);
}
